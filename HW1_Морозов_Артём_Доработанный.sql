-- нужно использовать COUNT(DISTINCT v.vacancy_id), чтобы считать уникальные вакансии.
-- Во-вторых, при делении count(r.response_id) / count(*) происходит целочисленное деление, поэтому дробная часть
-- результатов теряется. Чтобы она не терялось нужно числитель домножить на 1.0 и использовать ROUND для округления.
-- 3. В строке count(*) AS vacancies нужно использовать DISTINCT, так как у вакансии может быть много откликов
-- и т.к. count(*) считает строки после join, поэтому вместо подсчета уникальных вакансий мы получим
-- количество откликов.
-- 4. В строке sum(v.salary_from) AS total_salary неправильно считается общая зп, потому что
-- после join одна вакансия считается несколько раз (столько раз, сколько откликов) и в итоге, зарплата
-- одной вакансии считается несколько раз и получаются оченб большие суммы. 
-- 5. Последняя ошибка, которую я нашел, в строке с join. Обычный join равен inner join, а значит не добавляет в таблицу
-- вакансии у которых нет откликов, нужно использовать left join.
-- 6. Еще не совсем ошибка, но в строке GROUP BY нам на лекции говорили, что GROUP BY 1 группирует по первой колонке - это норм,
-- но лучше писать явно по какой колонке группируем, чтобы запрос проще читался.
-- 7. Еще как замечание: в знаменателе count(r.response_id) / count(*) нет nullif, который защищает от ошибки деления на ноль.
-- Хотя в этом запросе count(*) не может быть равен 0, все равно лучше использовать nullif.

-- Исправленный запрос:
SELECT 
	v.professional_role,
	count(DISTINCT v.vacancy_id) AS vacancies,
	ROUND(count(r.response_id) * 1.0 / NULLIF(count(DISTINCT v.vacancy_id), 0), 1) AS responses_per_vacancy
FROM vacancies v
LEFT JOIN responses r ON v.vacancy_id = r.vacancy_id
WHERE v.closed_at IS NULL
GROUP BY v.professional_role;

-- Запрос подсчета зарплатной метрики: средней минимальной зарплаты по профессии.
SELECT
	professional_role,
	ROUND(avg(salary_from),1) AS average_salary_from
FROM vacancies
WHERE closed_at IS NULL
GROUP BY professional_role;
-- Я решил заменить sum на avg, потому что сумма минимальных зарплат вакансий не дает 
-- полезной информации соискателю. 
-- avg(salary_from) более полезна для анализа рынка вакансий, так как показывает среднюю
-- нижнюю границу зарплат по каждому направлению. Соискатель может сравнивать предложения
-- по зп между профессиями и видеть, где предлагают больше.
-- Посчитал эту метрику отдельным запросом, потому что если добавить avg(salary_from) в основной
-- запрос с join, среднее будет считать неправильно (вакансии с большим количеством откликов 
-- влияли бы на итоговое значение). При этом avg не учитывает null, поэтому результат отражает
-- вакансии у которых salary_from указана.

