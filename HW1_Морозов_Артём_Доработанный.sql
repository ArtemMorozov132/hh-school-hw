SELECT
	professional_role,
	COUNT(*) AS vacancy_count,
	COUNT(DISTINCT employer_id) AS employers_count,
	ROUND(AVG(salary_from), 0) AS average_salary_from
FROM vacancies 
GROUP BY professional_role
ORDER BY vacancy_count DESC;

-- Запрос 2: то же, только направления с ≥ 5 открытыми вакансиями (WHERE + HAVING)
SELECT
	professional_role,
	COUNT(*) AS vacancy_count,
	COUNT(DISTINCT employer_id) AS employers_count,
	ROUND(AVG(salary_from), 0) AS average_salary_from
FROM vacancies 
WHERE closed_at IS NULL
GROUP BY professional_role
HAVING COUNT(*) >= 5
ORDER BY vacancy_count DESC;

-- Вывод:
-- 1) Больше половины рынка занимают аналитики данных (16 вакансий) и разработчики (15 вакансий),
