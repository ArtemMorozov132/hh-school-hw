-- Но этот запрос не учитывает статус вакансии (закрыта или открыта). После фильтрации WHERE closed_at IS NULL во втором запросе
-- остаются только открытые вакансии и например количество вакансий разработчика снижается почти вдвое (с 15 до 8).
-- 2) Where фильтрует строки до группировки, а having делает это уже после группировки.
-- Если напишем where count(*) >= 5, то выдаст ошибку потому что группы еще не построены
-- 3) avg(salary_from) показывает среднюю нижнюю границу зарплаты среди вакансий по направлениям, где указана 
-- salary_from (не учитываются значения null). Следовательно это среднее отражает только 
-- вакансии с указанной зарплатой и не дает возможность сделать вывод о среднем уровне 
-- зарплат по всем вакансиям направления.

-- ПРАВКА: 
-- Ответ на вопрос "почему одинаковый разрез дает разное количество вакансий?":
-- Разница возникает из-за фильтрации с where, а не из-за group by.
-- В первом запросе учитывались все вакансии, а во втором WHERE closed_at IS NULL
-- исключал закрытые вакансии до группировки.

-- Новый запрос: объединил total_vacancies (общее количество вакансий) и open_vacancies (количество открытых вакансий)
-- в одну таблицу, чтобы сравнить их в одном разрезе:
WITH total_vacancies_stats AS (
	SELECT
		professional_role,
		COUNT(*) AS total_vacancies
	FROM vacancies
	GROUP BY professional_role
),
open_vacancies_stats AS (
	SELECT 
		professional_role,
		COUNT(*) AS open_vacancies,
		ROUND(AVG(salary_from), 0) AS average_salary_from
	FROM vacancies
	WHERE closed_at IS NULL
	GROUP BY professional_role
)
SELECT
	t.professional_role,
	t.total_vacancies,
	COALESCE(o.open_vacancies, 0) AS open_vacancies,
	o.average_salary_from
FROM total_vacancies_stats AS t
LEFT JOIN open_vacancies_stats	AS o 
	ON t.professional_role = o.professional_role
ORDER BY t.total_vacancies DESC;
-- Вывод:
-- 1) Для оценки возможностей трудоустройства используем open_vacancies,
-- так как эта метрика показывает количество актуальных предложений.
-- total_vacancies полезна для оценки общего объема вакансий.
-- Для написания запроса использовал знания из 2 лекции, решил через CTE сделать, чтобы попрактиковаться).
-- 2) В первом cte (total_vacancies_stats) считаю общее количество вакансий, 
-- а во втором (open_vacancies_stats) открытые вакансии 
-- и среднюю зарплату (считаю среднюю зарплату по активным, так как
-- данные по ним важнее при аналитике зарплат для соискателя).
-- В конце объединяю результаты с помощью left join.
-- Благодаря использованию cte получилось разделить расчеты и избежать того,
-- чтобы where фильтровал всю таблицу и общее кол-во вакансий считалось неправильно.


